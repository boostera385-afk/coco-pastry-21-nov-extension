-- 2026-11-24
-- 1) Plan B call recording: the extension records Google Voice browser calls itself (no Workspace admin needed).
--    Files arrive before or after the call event, so they are matched to calls by time.
-- 2) Transcripts (in-browser Whisper on the dashboard, or Google's own) saved per call / voicemail.
-- 3) Per-agent shift (days + start/end in the business timezone) for shift reports and shift analysis rules.
-- 4) Analytics: busiest-times grid and per-agent team stats (talk time, in/off shift, recordings).

-- ---------- per-agent settings ----------
alter table agents add column if not exists record_calls boolean not null default true;
alter table agents add column if not exists shift_start time;          -- business timezone; null = no shift set
alter table agents add column if not exists shift_end   time;          -- end <= start means the shift crosses midnight
alter table agents add column if not exists shift_days  int[] not null default '{1,2,3,4,5}'; -- ISO weekday of the shift start

drop function if exists update_agent_settings(uuid, boolean, time, time, int[]);
create function update_agent_settings(p_agent uuid, p_record_calls boolean, p_shift_start time, p_shift_end time, p_shift_days int[])
returns void language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'admins only'; end if;
  if (p_shift_start is null) <> (p_shift_end is null) then raise exception 'set both shift start and end, or neither'; end if;
  if exists (select 1 from unnest(coalesce(p_shift_days, '{}')) d where d not between 1 and 7) then raise exception 'shift days are 1 (Mon) to 7 (Sun)'; end if;
  update agents set record_calls = coalesce(p_record_calls, record_calls), shift_start = p_shift_start, shift_end = p_shift_end,
                    shift_days = coalesce(p_shift_days, '{1,2,3,4,5}') where id = p_agent;
end $$;
revoke execute on function update_agent_settings(uuid, boolean, time, time, int[]) from public, anon;

-- ---------- extension-made call recordings ----------
create table if not exists call_recordings (
  id           uuid primary key,                 -- generated by the extension (idempotent re-uploads)
  agent_id     uuid not null references agents(id) on delete cascade,
  started_at   timestamptz not null,
  duration_sec int not null default 0,
  bytes        int,
  path         text not null,
  call_id      uuid references calls(id) on delete set null,
  created_at   timestamptz not null default now()
);
create index if not exists call_recordings_agent_started on call_recordings (agent_id, started_at);
create index if not exists call_recordings_unmatched on call_recordings (agent_id) where call_id is null;
alter table call_recordings enable row level security;
drop policy if exists "call_recordings: admins read" on call_recordings;
create policy "call_recordings: admins read" on call_recordings for select to authenticated using (is_admin());

alter table calls add column if not exists transcript_source text;   -- 'google' | 'whisper'
alter table calls add column if not exists transcribed_at timestamptz;
alter table messages add column if not exists transcript_source text;

-- Link recordings to calls: the call starts (dial / ring) up to 3 min before audio flows.
create or replace function match_call_recordings(p_agent uuid)
returns int language plpgsql security definer set search_path = public as $$
declare r record; v uuid; n int := 0;
begin
  for r in select * from call_recordings
            where agent_id = p_agent and call_id is null and started_at > now() - interval '7 days'
            order by started_at loop
    select k.id into v from calls k
     where k.agent_id = p_agent
       and k.occurred_at between r.started_at - interval '3 minutes' and r.started_at + interval '1 minute'
       and not exists (select 1 from call_recordings x where x.call_id = k.id)
     order by abs(extract(epoch from k.occurred_at - r.started_at)) limit 1;
    if v is not null then
      update call_recordings set call_id = v where id = r.id;
      update calls set recording_path = coalesce(recording_path, r.path) where id = v;  -- Google's own copy wins
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;
revoke execute on function match_call_recordings(uuid) from public, anon, authenticated;

-- ---------- transcripts ----------
create or replace function save_transcript(p_kind text, p_id uuid, p_text text, p_source text default 'whisper')
returns void language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'admins only'; end if;
  if p_kind = 'call' then
    update calls set transcript = nullif(trim(p_text), ''), transcript_source = p_source, transcribed_at = now() where id = p_id;
  elsif p_kind = 'voicemail' then
    update messages set body = nullif(trim(p_text), ''), transcript_source = p_source where id = p_id and kind = 'voicemail';
  else raise exception 'kind must be call or voicemail'; end if;
end $$;
revoke execute on function save_transcript(text, uuid, text, text) from public, anon;

-- Recordings that have audio but no text yet (newest first).
create or replace function transcription_queue(p_limit int default 50)
returns table (kind text, id uuid, recording_path text, occurred_at timestamptz, duration_sec int, agent_name text, contact text)
language sql stable security definer set search_path = public as $$
  select * from (
    select 'call'::text, k.id, k.recording_path, k.occurred_at, k.duration_sec, a.name, c.phone_e164
      from calls k join agents a on a.id = k.agent_id left join contacts c on c.id = k.contact_id
     where is_admin() and k.recording_path is not null and k.transcript is null
    union all
    select 'voicemail', m.id, m.recording_path, m.occurred_at, null, a.name, c.phone_e164
      from messages m join agents a on a.id = m.agent_id left join contacts c on c.id = m.contact_id
     where is_admin() and m.kind = 'voicemail' and m.recording_path is not null and coalesce(m.body, '') = ''
  ) q order by 4 desc limit greatest(1, least(p_limit, 500))
$$;

-- Conversation timeline: now with row id + transcript source (for the Transcribe button).
drop function if exists contact_timeline(uuid, uuid);
create function contact_timeline(p_agent uuid, p_contact uuid)
returns table (id uuid, kind text, direction text, outcome text, duration_sec int, conversation boolean, body text,
               occurred_at timestamptz, recording_path text, transcript_source text)
language sql stable security definer set search_path = public as $$
  select k.id, 'call', k.direction,
         case when k.direction = 'outbound' then (case when k.duration_sec > 0 then 'connected' else 'no_answer' end) else k.outcome end,
         k.duration_sec, (k.outcome in ('answered','connected') and k.duration_sec >= conversation_sec()), k.transcript, k.occurred_at,
         k.recording_path, k.transcript_source
    from calls k where is_manager() and k.agent_id = p_agent and k.contact_id is not distinct from p_contact
  union all
  select m.id, case when m.kind = 'voicemail' then 'voicemail' else 'text' end, m.direction, null, null, null, m.body, m.occurred_at,
         m.recording_path, m.transcript_source
    from messages m where is_manager() and m.agent_id = p_agent and m.contact_id is not distinct from p_contact
  order by occurred_at
$$;

-- Search inside call transcripts and voicemail text.
create or replace function search_transcripts(p_q text, p_from date, p_to date, p_agent uuid default null,
                                              p_from_ts timestamptz default null, p_to_ts timestamptz default null)
returns table (kind text, id uuid, agent_id uuid, agent_name text, contact_id uuid, contact text, occurred_at timestamptz, snippet text)
language sql stable security definer set search_path = public as $$
  with b as (select coalesce(p_from_ts, p_from::timestamp at time zone biz_tz()) t0, coalesce(p_to_ts, (p_to + 1)::timestamp at time zone biz_tz()) t1)
  select * from (
    select 'call'::text, k.id, k.agent_id, a.name, k.contact_id, c.phone_e164, k.occurred_at, left(k.transcript, 300)
      from calls k join agents a on a.id = k.agent_id left join contacts c on c.id = k.contact_id, b
     where k.transcript ilike '%' || p_q || '%' and k.occurred_at >= b.t0 and k.occurred_at < b.t1
    union all
    select 'voicemail', m.id, m.agent_id, a.name, m.contact_id, c.phone_e164, m.occurred_at, left(m.body, 300)
      from messages m join agents a on a.id = m.agent_id left join contacts c on c.id = m.contact_id, b
     where m.kind = 'voicemail' and m.body ilike '%' || p_q || '%' and m.occurred_at >= b.t0 and m.occurred_at < b.t1
  ) q
  where is_admin() and length(trim(coalesce(p_q, ''))) >= 2 and (p_agent is null or q.agent_id = p_agent)
  order by occurred_at desc limit 200
$$;

-- ---------- shifts ----------
-- One row per agent per scheduled shift that started in [p_from, p_to] (business dates) and has begun.
create or replace function shift_report(p_from date, p_to date, p_agent uuid default null)
returns table (agent_id uuid, agent_name text, day date, shift_from timestamptz, shift_to timestamptz, in_progress boolean,
               first_out timestamptz, last_out timestamptz, late_min numeric, early_min numeric,
               outbound bigint, inbound bigint, missed bigint, max_idle_min numeric)
language sql stable security definer set search_path = public as $$
  with sh as (
    select a.id, a.name, d::date as day,
           (d::date + a.shift_start) at time zone biz_tz() as s0,
           (d::date + a.shift_end + case when a.shift_end <= a.shift_start then interval '1 day' else interval '0' end) at time zone biz_tz() as s1
      from agents a, generate_series(p_from::timestamp, p_to::timestamp, interval '1 day') d
     where a.shift_start is not null and a.shift_end is not null
       and extract(isodow from d)::int = any (a.shift_days)
       and (is_admin() or a.id = my_agent_id()) and (p_agent is null or a.id = p_agent)
  )
  select sh.id, sh.name, sh.day, sh.s0, sh.s1, now() < sh.s1,
         x.first_out, x.last_out,
         case when x.first_out is not null then greatest(0, round((extract(epoch from x.first_out - sh.s0) / 60)::numeric)) end,
         case when now() >= sh.s1 and x.last_out is not null then greatest(0, round((extract(epoch from sh.s1 - x.last_out) / 60)::numeric)) end,
         coalesce(x.n_out, 0), coalesce(x.n_in, 0), coalesce(x.n_missed, 0), idle.m
    from sh
    left join lateral (
      select min(v.occurred_at) filter (where v.direction = 'outbound') as first_out,
             max(v.occurred_at) filter (where v.direction = 'outbound') as last_out,
             count(*) filter (where v.direction = 'outbound' and v.channel in ('call','text')) as n_out,
             count(*) filter (where v.direction = 'inbound') as n_in,
             count(*) filter (where v.channel = 'call' and v.direction = 'inbound' and v.outcome = 'missed') as n_missed
        from v_activity v where v.agent_id = sh.id and v.occurred_at >= sh.s0 and v.occurred_at < sh.s1) x on true
    left join lateral (   -- longest stretch without any outbound call/text inside the shift (so far)
      select round((max(g) / 60)::numeric) as m from (
        select extract(epoch from lead(t) over (order by t) - t) as g from (
          select sh.s0 as t
          union all select v.occurred_at from v_activity v
                     where v.agent_id = sh.id and v.direction = 'outbound' and v.occurred_at >= sh.s0 and v.occurred_at < sh.s1
          union all select least(sh.s1, now())) pts) gaps) idle on true
   where sh.s0 <= now()
   order by sh.s0 desc, sh.name
$$;

-- Shift rules for the Analysis page (same columns and review flow as analysis_issues).
create or replace function shift_issues(p_from date, p_to date, p_agent uuid default null)
returns table (issue_key text, rule text, severity text, agent_id uuid, agent_name text, contact_id uuid, contact text,
               conversation_id uuid, occurred_at timestamptz, detail text, delay_min numeric, status text, note text,
               reviewed_by text, reviewed_at timestamptz)
language sql stable security definer set search_path = public as $$
  with r as (select analysis_rules j from app_settings where id = 1),
  lim as (select coalesce((j->>'late_start_min')::int, 15) late, coalesce((j->>'early_end_min')::int, 15) early,
                 coalesce((j->>'idle_gap_min')::int, 60) idle from r),
  s as (select * from shift_report(p_from, p_to, p_agent)),
  issues as (
    select 'shift_none:' || s.agent_id || ':' || s.day as k, 'shift_no_activity' as rl, 'high' as sev, s.agent_id, s.agent_name,
           s.shift_from as at, 'No outbound calls or texts during the shift (' || to_char(s.shift_from at time zone biz_tz(), 'HH24:MI') || '–' ||
           to_char(s.shift_to at time zone biz_tz(), 'HH24:MI') || ')' as det, null::numeric as dly
      from s where not s.in_progress and s.first_out is null
    union all
    select 'shift_late:' || s.agent_id || ':' || s.day, 'shift_late_start', case when s.late_min > 60 then 'medium' else 'low' end, s.agent_id, s.agent_name,
           s.first_out, 'First outbound at ' || to_char(s.first_out at time zone biz_tz(), 'HH24:MI') || ', ' || s.late_min || ' min after shift start', s.late_min
      from s, lim where s.late_min > lim.late
    union all
    select 'shift_early:' || s.agent_id || ':' || s.day, 'shift_early_finish', case when s.early_min > 60 then 'medium' else 'low' end, s.agent_id, s.agent_name,
           s.last_out, 'Last outbound at ' || to_char(s.last_out at time zone biz_tz(), 'HH24:MI') || ', ' || s.early_min || ' min before shift end', s.early_min
      from s, lim where s.early_min > lim.early
    union all
    select 'shift_idle:' || s.agent_id || ':' || s.day, 'shift_idle_gap', case when s.max_idle_min > 2 * lim.idle then 'medium' else 'low' end, s.agent_id, s.agent_name,
           s.shift_from, 'Longest gap without outbound activity: ' || s.max_idle_min || ' min', s.max_idle_min
      from s, lim where s.first_out is not null and s.max_idle_min > lim.idle
  )
  select i.k, i.rl, i.sev, i.agent_id, i.agent_name, null::uuid, null::text, null::uuid, i.at, i.det, i.dly,
         coalesce(rv.status, 'open'), rv.note, u.email::text, rv.reviewed_at
    from issues i
    left join analysis_reviews rv on rv.issue_key = i.k
    left join auth.users u on u.id = rv.reviewed_by
   where is_admin()
   order by i.at desc
$$;

-- ---------- analytics ----------
-- Busiest times: weekday (1 Mon .. 7 Sun) x hour, business timezone.
create or replace function metrics_heatmap(p_from date, p_to date, p_agent uuid default null,
                                           p_from_ts timestamptz default null, p_to_ts timestamptz default null)
returns table (dow int, hour int, outbound_calls bigint, outbound_texts bigint, inbound_calls bigint, inbound_texts bigint, missed bigint, total bigint)
language sql stable security definer set search_path = public as $$
  with b as (select coalesce(p_from_ts, p_from::timestamp at time zone biz_tz()) t0, coalesce(p_to_ts, (p_to + 1)::timestamp at time zone biz_tz()) t1),
  act as (
    select v.*, extract(isodow from v.occurred_at at time zone biz_tz())::int d, extract(hour from v.occurred_at at time zone biz_tz())::int h
      from v_activity v, b
     where v.occurred_at >= b.t0 and v.occurred_at < b.t1
       and (is_admin() or v.agent_id = my_agent_id()) and (p_agent is null or v.agent_id = p_agent)
  )
  select d, h,
    count(*) filter (where channel = 'call' and direction = 'outbound'),
    count(*) filter (where channel = 'text' and direction = 'outbound'),
    count(*) filter (where (channel = 'call' or (channel = 'voicemail' and vm_call)) and direction = 'inbound'),
    count(*) filter (where channel = 'text' and direction = 'inbound'),
    count(*) filter (where channel = 'call' and direction = 'inbound' and outcome = 'missed'),
    count(*)
  from act group by d, h order by d, h
$$;

-- Extra per-agent numbers for the team table (joined with metrics_summary on the dashboard).
create or replace function team_stats(p_from date, p_to date, p_agent uuid default null,
                                      p_from_ts timestamptz default null, p_to_ts timestamptz default null)
returns table (agent_id uuid, talk_sec bigint, avg_call_sec numeric, answered_in bigint, voicemail_in bigint, short_calls bigint,
               recorded bigint, transcribed bigint, in_shift bigint, off_shift bigint, active_days bigint,
               first_at timestamptz, last_at timestamptz, has_shift boolean)
language sql stable security definer set search_path = public as $$
  with b as (select coalesce(p_from_ts, p_from::timestamp at time zone biz_tz()) t0, coalesce(p_to_ts, (p_to + 1)::timestamp at time zone biz_tz()) t1),
  scope as (select a.* from agents a where (is_admin() or a.id = my_agent_id()) and (p_agent is null or a.id = p_agent)),
  sh as (   -- shift windows that can overlap the range (start the day before, for overnight shifts)
    select a.id, (d::date + a.shift_start) at time zone biz_tz() s0,
           (d::date + a.shift_end + case when a.shift_end <= a.shift_start then interval '1 day' else interval '0' end) at time zone biz_tz() s1
      from scope a, generate_series(p_from::timestamp - interval '1 day', p_to::timestamp, interval '1 day') d
     where a.shift_start is not null and a.shift_end is not null and extract(isodow from d)::int = any (a.shift_days)
  ),
  k as (select c.* from calls c, b where c.agent_id in (select id from scope) and c.occurred_at >= b.t0 and c.occurred_at < b.t1),
  out_ev as (
    select v.agent_id, v.occurred_at, exists (select 1 from sh where sh.id = v.agent_id and v.occurred_at >= sh.s0 and v.occurred_at < sh.s1) ins
      from v_activity v, b
     where v.agent_id in (select id from scope) and v.direction = 'outbound' and v.channel in ('call','text')
       and v.occurred_at >= b.t0 and v.occurred_at < b.t1
  ),
  rs as (select analysis_rules j from app_settings where id = 1)
  select s.id,
    coalesce((select sum(duration_sec) from k where k.agent_id = s.id), 0),
    (select round(avg(duration_sec)::numeric) from k where k.agent_id = s.id and duration_sec > 0),
    (select count(*) from k where k.agent_id = s.id and direction = 'inbound' and outcome = 'answered'),
    (select count(*) from v_activity v, b where v.agent_id = s.id and v.channel = 'voicemail' and v.vm_call and v.occurred_at >= b.t0 and v.occurred_at < b.t1),
    (select count(*) from k, rs where k.agent_id = s.id and direction = 'outbound' and duration_sec between 1 and coalesce((rs.j->>'short_call_sec')::int, 15) - 1),
    (select count(*) from k where k.agent_id = s.id and recording_path is not null),
    (select count(*) from k where k.agent_id = s.id and transcript is not null),
    (select count(*) from out_ev o where o.agent_id = s.id and o.ins),
    (select count(*) from out_ev o where o.agent_id = s.id and not o.ins),
    (select count(distinct (o.occurred_at at time zone biz_tz())::date) from out_ev o where o.agent_id = s.id),
    (select min(occurred_at) from out_ev o where o.agent_id = s.id),
    (select max(occurred_at) from out_ev o where o.agent_id = s.id),
    s.shift_start is not null
  from scope s
$$;

